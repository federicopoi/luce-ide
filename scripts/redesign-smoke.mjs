import {_electron as electron} from 'playwright';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
const root=await mkdtemp(path.join(os.tmpdir(),'luce-redesign-'));
const folder=path.join(root,'Smoke'),other=path.join(root,'Fantasy Fit');
await mkdir(folder);await mkdir(other);await mkdir('artifacts',{recursive:true});
let app;
async function until(fn){for(let i=0;i<150;i++){if(await fn())return;await new Promise(r=>setTimeout(r,50));}throw Error('Timed out');}
try{
 const options={args:[path.resolve('.')],env:{...process.env,SHELL:'/bin/bash',LUCE_TEST:'1',LUCE_PROFILE:path.join(root,'profile'),LUCE_HISTORY_HOME:path.join(root,'history')}};
 if(process.env.LUCE_EXECUTABLE){options.executablePath=process.env.LUCE_EXECUTABLE;options.args=[];}
 app=await electron.launch(options);const page=await app.firstWindow();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await until(()=>page.evaluate(async()=>!!window.luce&&!(await window.luce.getState()).workspaceRestoring));
 const p=await page.evaluate(dir=>window.luce.addProject(dir),folder);
 await page.locator('.project-item.selected').waitFor();
 const a=await page.locator('#project-sidebar').boundingBox(),b=await page.locator('#conversation-sidebar').boundingBox();
 assert.ok(Math.abs(a.x-b.x)<40&&b.x+b.width<=a.x+a.width+1,'Projects and conversations share a single navigation column');
 assert.equal(await page.locator('#terminal-workspace .welcome').count(),1,'Empty project has one start view');
 assert.equal(await page.locator('#terminal-workspace .pane-empty').count(),0);
 await page.getByRole('textbox',{name:'Search conversations',exact:true}).focus();
 await page.screenshot({path:'artifacts/redesign-empty.png'});
 await page.locator('.provider-choices [data-provider="shell"]').click();
 await until(()=>page.evaluate(async()=>(await window.luce.getState()).terminals.length===1));
 const s=(await page.evaluate(()=>window.luce.getState())).terminals[0];
 await page.evaluate(id=>window.luce.renameTerminal(id,'Build landing page'),s.id);
 await page.locator(`[data-session-id="${s.id}"] .xterm`).waitFor();
 const q=await page.evaluate(dir=>window.luce.addProject(dir),other);
 await page.locator(`.project-item[data-project-id="${p.id}"]`).click();
 await page.locator(`#conversation-sidebar [data-session-id="${s.id}"]`).click();
 assert.equal((await page.evaluate(()=>window.luce.getState())).selectedProjectId,p.id);
 await page.getByRole('button',{name:'Toggle project list'}).click();
 assert.equal(await page.locator('#projects').isVisible(),false);
 assert.equal(await page.locator(`#conversation-sidebar [data-session-id="${s.id}"]`).isVisible(),true,'Folding project rows retains access to the active conversation');
 await page.getByRole('button',{name:'Toggle project list'}).click();
 const beforeSessions=(await page.evaluate(()=>window.luce.getState())).terminals.length;
 const emptyPane=page.locator('#terminal-workspace > .terminal-pane[data-layout-slot="3"]');
 await emptyPane.getByRole('button',{name:'New conversation'}).click();
 await page.locator('#popup').getByRole('button',{name:'Project shell'}).click();
 await until(()=>page.evaluate(async n=>(await window.luce.getState()).terminals.length===n+1,beforeSessions));
 await page.locator('#terminal-workspace > .terminal-pane[data-layout-slot="3"] .xterm').waitFor();
 await page.getByRole('button',{name:'Browse project files'}).click();await page.locator('#file-sidebar').waitFor({state:'visible'});
 await page.getByRole('button',{name:'Close files sidebar'}).click();
 await page.getByRole('button',{name:'Collapse projects sidebar'}).click();
 assert.equal(await page.locator('#project-sidebar').isVisible(),false);
 await page.getByRole('button',{name:'Show projects sidebar'}).click();
 assert.equal(await page.locator('#conversation-sidebar').isVisible(),true);
 const width=(await page.locator('#project-sidebar').boundingBox()).width;
 await page.getByRole('separator',{name:'Resize projects sidebar',exact:true}).focus();await page.keyboard.press('ArrowRight');
 assert.ok((await page.locator('#project-sidebar').boundingBox()).width>width);
 await page.getByRole('button',{name:'Toggle project view'}).click();await page.locator('#project-tabs').waitFor({state:'visible'});
 await page.getByRole('tab',{name:/Fantasy Fit/}).click();assert.equal((await page.evaluate(()=>window.luce.getState())).selectedProjectId,q.id);
 assert.equal(await page.locator('#conversation-sidebar').isVisible(),true);
 await page.getByRole('button',{name:'Toggle project view'}).click();
 await page.locator(`.project-item[data-project-id="${p.id}"]`).click();
 await page.screenshot({path:'artifacts/redesign-workspace.png'});
 await page.getByRole('button',{name:'Accounts',exact:true}).click();await page.locator('#modal').waitFor({state:'visible'});
 await page.screenshot({path:'artifacts/redesign-accounts.png'});await page.getByRole('button',{name:'Close dialog'}).click();
 await page.getByRole('button',{name:'Phone',exact:true}).click();await page.locator('#remote-settings').waitFor();await page.getByRole('button',{name:'Close dialog'}).click();
 await page.getByRole('button',{name:'Settings',exact:true}).click();await page.screenshot({path:'artifacts/redesign-settings.png'});await page.getByRole('button',{name:'Close dialog'}).click();
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(960,680));
 await until(()=>page.evaluate(()=>innerWidth===960));
 assert.ok((await page.locator('.workspace').boundingBox()).width>500,'Smaller windows keep usable terminal space');
 assert.deepEqual(errors,[]);console.log('PASS: unified navigation, empty project, terminal/project switching, files, collapse/resize, tabs, accounts and smaller windows.');
}finally{if(app)await app.close();await rm(root,{recursive:true,force:true});}
